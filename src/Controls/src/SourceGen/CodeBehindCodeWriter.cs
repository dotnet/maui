	internal static readonly string[] accessModifiers = ["private", "public", "internal", "protected"];

	public static string GenerateXamlCodeBehind(XamlProjectItemForCB? xamlItem, Compilation compilation, Action<Diagnostic>? reportDiagnostic, CancellationToken ct, AssemblyAttributes xmlnsCache, IDictionary<XmlType, INamedTypeSymbol> typeCache)
	{
		var projItem = xamlItem?.ProjectItem;

		// Get a unique string for this xaml project item
		var itemName = projItem?.ManifestResourceName ?? projItem?.RelativePath;
		if (itemName == null)
			return "";

		if (xamlItem!.Root == null)
		{
			if (xamlItem.Exception != null)
			{
				reportDiagnostic?.Invoke(XamlDiagnosticHelpers.CreateXamlParserDiagnostic(projItem, xamlItem.SourceText, xamlItem.Exception));
			}
			return "";
		}

		var codeBlocks = GetCodeBlocks(xamlItem, compilation, reportDiagnostic, ct);
		var uid = Crc64.ComputeHashString($"{compilation.AssemblyName}.{itemName}");
		if (!TryParseXaml(xamlItem, uid, compilation, xmlnsCache, typeCache, ct, reportDiagnostic, out var accessModifier, out var rootType, out var rootClrNamespace, out var generateDefaultCtor, out var addXamlCompilationAttribute, out var hideFromIntellisense, out var XamlResourceIdOnly, out var baseType, out var namedFields))
		{
			return "";
		}

		var eventHandlerAccessor = GetEventHandlerAccessor(projItem, compilation);

		// Preserve prior fields for EnC, but do not assign fields without a compatible live element.
		var fieldState = ReconcileNamedFieldsForHotReload(projItem!, compilation, ref namedFields);

		var sb = new StringBuilder();
		sb.AppendLine(AutoGeneratedHeaderText);
		var warningDisable = GetWarningDisable(xamlItem.Root.OwnerDocument);
		if (warningDisable != "")
			sb.AppendLine($"#pragma warning disable {warningDisable}");

		// Inline code follows the project's nullable context, not the generated-code default.
		var hasUsings = codeBlocks.Any(block => block.Usings.Length > 0);
		if (hasUsings)
			sb.AppendLine("#nullable restore");
		foreach (var directive in codeBlocks.SelectMany(block => block.Usings).OrderByDescending(directive => directive.IsGlobal))
		{
			if (projItem!.EnableLineInfo)
				sb.AppendLine($"#line {directive.LineNumber} {SymbolDisplay.FormatLiteral(projItem.AdditionalText.Path, true)}");
			sb.AppendLine(directive.Text);
			if (projItem!.EnableLineInfo)
				sb.AppendLine("#line default");
		}
		if (hasUsings)
			sb.AppendLine("#nullable disable");

		var hintName = $"{(string.IsNullOrEmpty(Path.GetDirectoryName(projItem!.TargetPath)) ? "" : Path.GetDirectoryName(projItem.TargetPath) + Path.DirectorySeparatorChar)}{Path.GetFileNameWithoutExtension(projItem.TargetPath)}.{projItem.Kind.ToLowerInvariant()}.sg.cs".Replace(Path.DirectorySeparatorChar, '_');

		if (projItem.ManifestResourceName != null && projItem.RelativePath != null)
		{
			sb.AppendLine($"[assembly: global::Microsoft.Maui.Controls.Xaml.XamlResourceId(\"{projItem.ManifestResourceName}\", \"{projItem.RelativePath.Replace('\\', '/')}\", {(rootType == null ? "null" : "typeof(global::" + rootClrNamespace + "." + rootType + ")")})]");
		}

		if (XamlResourceIdOnly)
		{
			return sb.ToString();
		}

		if (rootType == null)
		{
			throw new Exception("Something went wrong");
		}

		var rootSymbol = compilation.GetTypeByMetadataName($"{rootClrNamespace}.{rootType}");
		bool alreadyHasXamlCompilationAttribute = rootSymbol?.GetAttributes().Any(a => a.AttributeClass != null && a.AttributeClass.Equals(compilation.GetTypeByMetadataName("Microsoft.Maui.Controls.Xaml.XamlCompilationAttribute")!, SymbolEqualityComparer.Default)) ?? false;

		var generateInflatorSwitch = compilation.AssemblyName == "Microsoft.Maui.Controls.Xaml.UnitTests" && !generateDefaultCtor;
		var xamlInflators = projItem.Inflator;

		//if there's only the XamlC inflator, prevent non-assigned errors
		if (xamlInflators == XamlInflator.XamlC)
			sb.AppendLine("#pragma warning disable CS0649");

		sb.AppendLine($"namespace {rootClrNamespace}");
		sb.AppendLine("{");
		sb.AppendLine($"\t[global::Microsoft.Maui.Controls.Xaml.XamlFilePath(\"{projItem.RelativePath?.Replace("\\", "\\\\")}\")]");

#pragma warning disable CS0618 // XamlCompilation is deprecated but still generated for backcompat
		if (!addXamlCompilationAttribute && (xamlInflators & XamlInflator.XamlC) == 0 && !alreadyHasXamlCompilationAttribute)
			sb.AppendLine($"\t#pragma warning disable CS0618\n\t[global::Microsoft.Maui.Controls.Xaml.XamlCompilation(global::Microsoft.Maui.Controls.Xaml.XamlCompilationOptions.Skip)]\n\t#pragma warning restore CS0618");
#pragma warning restore CS0618

		if (hideFromIntellisense)
		{
			sb.AppendLine($"\t[global::System.ComponentModel.EditorBrowsable(global::System.ComponentModel.EditorBrowsableState.Never)]");
		}

		if (generateDefaultCtor)
			sb.AppendLine($"\t[global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.Maui.Controls.SourceGen\", \"1.0.0.0\")]");

		sb.AppendLine($"\t{accessModifier} partial class {rootType} : {baseType!.ToFQDisplayString()}");
		sb.AppendLine("\t{");

		if (eventHandlerAccessor is not null)
		{
			const string tableType = "global::System.Runtime.CompilerServices.ConditionalWeakTable<object, global::System.Collections.Generic.Dictionary<string, global::System.Delegate>>";
			sb.AppendLine($"\t\tprivate {tableType} {eventHandlerAccessor}_table = null!;");
			sb.AppendLine($"\t\tprivate {tableType} {eventHandlerAccessor}() => {eventHandlerAccessor}_table ??= new();");
		}

		if (codeBlocks.Count > 0)
			sb.AppendLine("#nullable restore");
		foreach (var block in codeBlocks)
		{
			if (projItem.EnableLineInfo)
				sb.AppendLine($"#line {block.LineNumber} {SymbolDisplay.FormatLiteral(projItem.AdditionalText.Path, true)}");
			sb.AppendLine(block.Members);
			if (projItem.EnableLineInfo)
				sb.AppendLine("#line default");
		}
		if (codeBlocks.Count > 0)
			sb.AppendLine("#nullable disable");

		//optional default ctor
		if (generateDefaultCtor)
		{
			sb.AppendLine($"\t\t[global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.Maui.Controls.SourceGen\", \"1.0.0.0\")]");
			sb.AppendLine($"\t\tpublic {rootType}() => InitializeComponent();");
			sb.AppendLine();
		}

		//create fields
		if (namedFields != null)
		{
			//with XamlC, the body of the ctor is empty when the compiler is done, raising warnings. disable those
			if (!generateInflatorSwitch
				&& ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC
					|| (projItem.Configuration != null && projItem.Configuration.Equals("Release", StringComparison.OrdinalIgnoreCase))))
				sb.AppendLine("#pragma warning disable CS0169, CS0649");

			foreach ((var fname, var ftype, var faccess, _, _) in namedFields)
			{
				sb.AppendLine($"\t\t[global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.Maui.Controls.SourceGen\", \"1.0.0.0\")]");

				if (fieldState.GhostFieldNames.Contains(fname) || fieldState.ConditionallyAssignedFieldNames.Contains(fname))
					sb.AppendLine($"\t\t{faccess} {ftype} {EscapeIdentifier(fname)} = default!;");
				else
					sb.AppendLine($"\t\t{faccess} {ftype} {EscapeIdentifier(fname)};");
				sb.AppendLine();
			}
			if (!generateInflatorSwitch
				&& ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC
					|| (projItem.Configuration != null && projItem.Configuration.Equals("Release", StringComparison.OrdinalIgnoreCase))))
				sb.AppendLine("#pragma warning restore CS0169, CS0649");
		}

		// if the generateInflatorSwitch is false, we will, depending on the value of inflators
		// - treat XamlInflator.Default as XamlInflator.Runtime for Debug, and XamlC for Release
		// - generate InitializeComponent() with the LoadFromXaml call for XamlInflator.Runtime
		// - generate an empty InitializeComponent for XamlInflator.XamlC (XamlC will replace the methodbody later)
		// - generate the partial signature for InitializeComponent for XamlInflator.SourceGen

		// if the generateInflatorSwitch is true, we will generate a switch statement in the constructor
		// that will call the correct InitializeComponent method depending on the inflator passed in
		// XamlInflatorDefault means all
		// - InitializeCompnentRuntime will be used for Runtime
		// - InitializeComponentXamlC will be used for XamlC
		// - InitializeComponentSourceGen will be used for SourceGen
		// - no parameterless InitializeComponent will be generated
		if (!generateInflatorSwitch)
		{
			if ((xamlInflators & XamlInflator.Runtime) == XamlInflator.Runtime)
				InitComp("InitializeComponent");
			else if ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC)
				InitComp("InitializeComponent");
			else if ((xamlInflators & XamlInflator.SourceGen) == XamlInflator.SourceGen)
			{
				InitComp("InitializeComponent", partialsignature: true);
				//generate InitCompRuntime for HotReload fallback
				if (projItem.EnableDiagnostics && projItem.EnableHotReload)
					InitComp("InitializeComponentRuntime");
			}
		}
		else
		{
			if ((xamlInflators & XamlInflator.Runtime) == XamlInflator.Runtime || (projItem.EnableDiagnostics && projItem.EnableHotReload))
				InitComp("InitializeComponentRuntime");
			if ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC)
				InitComp("InitializeComponentXamlC", empty: true);
			if ((xamlInflators & XamlInflator.SourceGen) == XamlInflator.SourceGen)
				InitComp("InitializeComponentSourceGen", partialsignature: true);
		}

		//initializeComponent
		void InitComp(string methodName, bool empty = false, bool partialsignature = false)
		{
			sb.AppendLine($"\t\t[global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.Maui.Controls.SourceGen\", \"1.0.0.0\")]");
			// add MemberNotNull attributes
			if (namedFields != null && namedFields.Any(f => !fieldState.GhostFieldNames.Contains(f.Item1) && !fieldState.ConditionallyAssignedFieldNames.Contains(f.Item1)))
			{
				sb.AppendLine($"#if NET5_0_OR_GREATER");
				foreach ((var fname, _, _, _, _) in namedFields)
				{
					if (!fieldState.GhostFieldNames.Contains(fname) && !fieldState.ConditionallyAssignedFieldNames.Contains(fname))
						sb.AppendLine($"\t\t[global::System.Diagnostics.CodeAnalysis.MemberNotNullAttribute(nameof({EscapeIdentifier(fname)}))]");
				}

				sb.AppendLine($"#endif");
			}

			if (empty)
				sb.AppendLine("#nullable disable");

			var modifier = partialsignature ? "partial " : "";
			var semicolon = partialsignature ? ";" : "";
			sb.AppendLine($"\t\tprivate {modifier}void {methodName}(){semicolon}");
			if (partialsignature)
			{
				sb.AppendLine();
				return;
			}

			sb.AppendLine("\t\t{");
			if (!empty)
			{
				sb.AppendLine("#pragma warning disable IL2026, IL3050 // The body of InitializeComponent will be replaced by XamlC so LoadFromXaml will never be called in production builds");
				sb.AppendLine($"\t\t\tglobal::Microsoft.Maui.Controls.Xaml.Extensions.LoadFromXaml(this, typeof({rootType}));");

				if (namedFields != null)
				{
					var conditionalFieldIndex = 0;
					foreach ((var fname, var ftype, _, _, var xamlName) in namedFields)
					{
						if (fieldState.GhostFieldNames.Contains(fname))
							continue;
						if (fieldState.ConditionallyAssignedFieldNames.Contains(fname))
						{
							var valueName = $"__xamlField{conditionalFieldIndex++}";
							sb.AppendLine($"\t\t\tif (global::Microsoft.Maui.Controls.NameScopeExtensions.FindByName<object>(this, {SymbolDisplay.FormatLiteral(xamlName, true)}) is {ftype} {valueName})");
							sb.AppendLine($"\t\t\t\t{EscapeIdentifier(fname)} = {valueName};");
						}
						else
						{
							sb.AppendLine($"\t\t\t{EscapeIdentifier(fname)} = global::Microsoft.Maui.Controls.NameScopeExtensions.FindByName<{ftype}>(this, {SymbolDisplay.FormatLiteral(xamlName, true)});");
						}
					}
				}
				sb.AppendLine("#pragma warning restore IL2026, IL3050");
			}
			sb.AppendLine("\t\t}");

			if (empty)
			{
				sb.AppendLine("#nullable enable");
			}

			sb.AppendLine();
		}

		if (generateInflatorSwitch)
		{
			sb.AppendLine();

			// add MemberNotNull attributes
			if (namedFields != null && namedFields.Any(f => !fieldState.GhostFieldNames.Contains(f.Item1) && !fieldState.ConditionallyAssignedFieldNames.Contains(f.Item1)))
			{
				sb.AppendLine($"#if NET5_0_OR_GREATER");
				foreach ((var fname, _, _, _, _) in namedFields)
				{
					if (!fieldState.GhostFieldNames.Contains(fname) && !fieldState.ConditionallyAssignedFieldNames.Contains(fname))
						sb.AppendLine($"\t\t[global::System.Diagnostics.CodeAnalysis.MemberNotNullAttribute(nameof({EscapeIdentifier(fname)}))]");
				}

				sb.AppendLine($"#endif");
			}

			//this isn't supposed to be used, so the default to the first available inflator
			if ((xamlInflators & XamlInflator.Runtime) == XamlInflator.Runtime)
				sb.AppendLine($"\t\tprivate void InitializeComponent() => InitializeComponentRuntime();");
			else if ((xamlInflators & XamlInflator.SourceGen) == XamlInflator.SourceGen)
				sb.AppendLine($"\t\tprivate void InitializeComponent() => InitializeComponentSourceGen();");
			else if ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC)
				sb.AppendLine($"\t\tprivate void InitializeComponent() => InitializeComponentXamlC();");


			sb.AppendLine($"\t\t[global::System.CodeDom.Compiler.GeneratedCode(\"Microsoft.Maui.Controls.SourceGen\", \"1.0.0.0\")]");

			sb.AppendLine($"\t\tinternal {rootType}(global::Microsoft.Maui.Controls.Xaml.XamlInflator inflator)");
			sb.AppendLine("\t\t{");
			sb.AppendLine("\t\t\tswitch (inflator)");
			sb.AppendLine("\t\t\t{");
			if ((xamlInflators & XamlInflator.Runtime) == XamlInflator.Runtime)
			{
				sb.AppendLine("\t\t\t\tcase global::Microsoft.Maui.Controls.Xaml.XamlInflator.Runtime:");
				sb.AppendLine("\t\t\t\t\tInitializeComponentRuntime();");
				sb.AppendLine("\t\t\t\t\tbreak;");
			}
			if ((xamlInflators & XamlInflator.XamlC) == XamlInflator.XamlC)
			{
				sb.AppendLine("\t\t\t\tcase global::Microsoft.Maui.Controls.Xaml.XamlInflator.XamlC:");
				sb.AppendLine("\t\t\t\t\tInitializeComponentXamlC();");
				sb.AppendLine("\t\t\t\t\tbreak;");
			}
			if ((xamlInflators & XamlInflator.SourceGen) == XamlInflator.SourceGen)
			{
				sb.AppendLine("\t\t\t\tcase global::Microsoft.Maui.Controls.Xaml.XamlInflator.SourceGen:");
				sb.AppendLine("\t\t\t\t\tInitializeComponentSourceGen();");
				sb.AppendLine("\t\t\t\t\tbreak;");
			}
			sb.AppendLine("\t\t\t\tdefault:");
			sb.AppendLine("\t\t\t\t\tthrow new global::System.NotSupportedException($\"no code for {inflator} generated. check the [XamlProcessing] attribute.\");");
			sb.AppendLine("\t\t\t}");
			sb.AppendLine("\t\t}");
		}
		sb.AppendLine("\t}");
		sb.AppendLine("}");

		return sb.ToString();
	}

	readonly record struct CodeUsing(string Text, int LineNumber, bool IsGlobal);
	readonly record struct CodeBlock(string Members, int LineNumber, CodeUsing[] Usings);

	internal static string? GetEventHandlerAccessor(ProjectItem? projectItem, Compilation compilation)
	{
		if (projectItem is null || !projectItem.EnableIncrementalHotReload)
			return null;

		var itemName = projectItem.ManifestResourceName ?? projectItem.RelativePath;
		if (itemName is null)
			return null;

		return $"__GetXamlEventHandlers_{Crc64.ComputeHashString($"{compilation.AssemblyName}.{itemName}")}";
	}

	static List<CodeBlock> GetCodeBlocks(XamlProjectItemForCB item, Compilation compilation, Action<Diagnostic>? reportDiagnostic, CancellationToken cancellationToken)
	{
		var blocks = new List<CodeBlock>();
		var source = item.SourceText!;
		var xaml = source.ToString();
		if (xaml.IndexOf("Code", StringComparison.Ordinal) < 0)
			return blocks;

		var projectItem = item.ProjectItem!;
		var namespaces = item.Nsmgr!;
		using var reader = XmlReader.Create(new StringReader(xaml),
			new XmlReaderSettings { ConformanceLevel = ConformanceLevel.Fragment },
			new XmlParserContext(namespaces.NameTable, namespaces, null, XmlSpace.None));
		var hasClass = false;
		while (reader.Read())
		{
			cancellationToken.ThrowIfCancellationRequested();
			if (reader.NodeType != XmlNodeType.Element)
				continue;
			if (reader.Depth == 0)
				hasClass = reader.GetAttribute("Class", XamlParser.X2006Uri) != null || reader.GetAttribute("Class", XamlParser.X2009Uri) != null;
			if (reader.LocalName != "Code" || (reader.NamespaceURI != XamlParser.X2006Uri && reader.NamespaceURI != XamlParser.X2009Uri))
				continue;

			var lineInfo = (IXmlLineInfo)reader;
			var line = lineInfo.LineNumber;
			var column = lineInfo.LinePosition;
			var sourceLine = source.Lines[line - 1];
			var start = Math.Min(sourceLine.Start + column - 1, sourceLine.End);
			var span = new TextSpan(start, Math.Min(reader.Name.Length, source.Length - start));
			var location = Location.Create(projectItem.AdditionalText.Path, span, source.Lines.GetLinePositionSpan(span));
			var validPlacement = reader.Depth == 1 && hasClass;
			if (reader.Depth != 1)
				reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XCodeNotChildOfRoot, location));
			else if (!hasClass)
				reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XCodeRequiresXClass, location));
			else
			{
				if (projectItem.Inflator != XamlInflator.SourceGen)
					reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XCodeRequiresSourceGen, location));
				if (!projectItem.EnablePreviewFeatures)
					reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XCodeRequiresPreview, location));
			}

			var content = new StringBuilder();
			var contentLine = line;
			var nextLine = line;
			var hasContent = false;
			var hasElement = false;
			using (var subtree = reader.ReadSubtree())
			{
				while (subtree.Read())
				{
					if (subtree.Depth == 0)
						continue;
					if (subtree.NodeType == XmlNodeType.Element)
						hasElement = true;
					if (subtree.NodeType is not (XmlNodeType.Text or XmlNodeType.CDATA or XmlNodeType.Whitespace or XmlNodeType.SignificantWhitespace))
						continue;
					if (!hasContent)
					{
						contentLine = ((IXmlLineInfo)subtree).LineNumber;
						nextLine = contentLine;
						hasContent = true;
					}
					while (nextLine < ((IXmlLineInfo)subtree).LineNumber)
					{
						content.Append('\n');
						nextLine++;
					}
					content.Append(subtree.Value);
					foreach (var character in subtree.Value)
						if (character == '\n')
							nextLine++;
				}
			}
			if (hasElement)
			{
				reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XamlParserError, location, "x:Code must contain only text or CDATA."));
				continue;
			}
			if (!validPlacement)
				continue;

			var code = content.ToString();
			var parseOptions = (compilation.SyntaxTrees.FirstOrDefault()?.Options as CSharpParseOptions ?? CSharpParseOptions.Default)
				.WithKind(SourceCodeKind.Script);
			var syntax = CSharpSyntaxTree.ParseText(code, parseOptions, cancellationToken: cancellationToken).GetCompilationUnitRoot(cancellationToken);
			var members = code.ToCharArray();
			foreach (var directive in syntax.Usings)
				for (var i = directive.SpanStart; i < directive.Span.End; i++)
					if (members[i] != '\r' && members[i] != '\n')
						members[i] = ' ';
			blocks.Add(new CodeBlock(new string(members), contentLine, syntax.Usings
				.Select(u => new CodeUsing(u.ToString(), contentLine + u.GetLocation().GetLineSpan().StartLinePosition.Line, u.GlobalKeyword.IsKind(SyntaxKind.GlobalKeyword)))
				.ToArray()));
		}
		return blocks;
	}

	public static bool TryParseXaml(XamlProjectItemForCB parseResult, string uid, Compilation compilation, AssemblyAttributes xmlnsCache, IDictionary<XmlType, INamedTypeSymbol> typeCache, CancellationToken cancellationToken, Action<Diagnostic>? reportDiagnostic, out string? accessModifier, out string? rootType, out string? rootClrNamespace, out bool generateDefaultCtor, out bool addXamlCompilationAttribute, out bool hideFromIntellisense, out bool xamlResourceIdOnly, out INamedTypeSymbol? baseType, out IEnumerable<(string, string, string, XmlType, string)>? namedFields)
	{
		accessModifier = null;
		rootType = null;
		rootClrNamespace = null;
		generateDefaultCtor = false;
		addXamlCompilationAttribute = false;
		hideFromIntellisense = false;
		xamlResourceIdOnly = false;
		namedFields = null;
		baseType = null;

		cancellationToken.ThrowIfCancellationRequested();

		var root = parseResult.Root;
		var nsmgr = parseResult.Nsmgr;

		if (root == null || nsmgr == null)
		{
			return false;
		}

#if !NET12_0_OR_GREATER
		// if the following xml processing instruction is present
		//
		// <?xaml-comp compile="true" ?>
		//
		// we will generate a xaml.g.cs file with the default ctor calling InitializeComponent, and a XamlCompilation attribute
		var hasXamlCompilationProcessingInstruction = GetXamlCompilationProcessingInstruction(root.OwnerDocument);
#endif

		var rootClass = root.Attributes["Class", XamlParser.X2006Uri]
					 ?? root.Attributes["Class", XamlParser.X2009Uri];

		if (rootClass != null)
		{
			XmlnsHelper.ParseXmlns(rootClass.Value, out rootType, out rootClrNamespace, out _, out _);
		}
#if !NET12_0_OR_GREATER
		else if (hasXamlCompilationProcessingInstruction
				&& (root.NamespaceURI == XamlParser.MauiUri || root.NamespaceURI == XamlParser.MauiGlobalUri))
#else
		else if (root.NamespaceURI == XamlParser.MauiUri || root.NamespaceURI == XamlParser.MauiGlobalUri)
#endif
		{
			//make sure the base type can be resolved. if not, don't consider this as xaml, and move away
			var typeArgs = GetAttributeValue(root, "TypeArguments", XamlParser.X2006Uri, XamlParser.X2009Uri);
			try
			{
				var basetype = new XmlType(root.NamespaceURI, root.LocalName, typeArgs != null ? TypeArgumentsParser.ParseExpression(typeArgs, nsmgr, null) : null).GetTypeSymbol(null, compilation, xmlnsCache, typeCache);
			}
			catch
			{
				return false;
			}

			rootClrNamespace = "__XamlGeneratedCode__";
			rootType = $"__Type{uid}";
			generateDefaultCtor = true;
			addXamlCompilationAttribute = true;
			hideFromIntellisense = true;
		}
		else if (parseResult?.ProjectItem?.ManifestResourceName != null && parseResult.ProjectItem.TargetPath != null)
		{ // rootClass == null && !hasXamlCompilationProcessingInstruction) {
			xamlResourceIdOnly = true; //only generate the XamlResourceId assembly attribute
			return true;
		}
		else
		{
			reportDiagnostic?.Invoke(Diagnostic.Create(Descriptors.XamlParserError, Location.None, $"Xaml file {parseResult?.ProjectItem?.RelativePath} does not have a Class attribute"));
			return false;
		}

		namedFields = GetNamedFields(root, nsmgr, compilation, xmlnsCache, typeCache, cancellationToken, reportDiagnostic);
		var typeArguments = GetAttributeValue(root, "TypeArguments", XamlParser.X2006Uri, XamlParser.X2009Uri);
		baseType = new XmlType(root.NamespaceURI, root.LocalName, typeArguments != null ? TypeArgumentsParser.ParseExpression(typeArguments, nsmgr, null) : null).GetTypeSymbol(reportDiagnostic, compilation, xmlnsCache, typeCache);

		// x:ClassModifier attribute
		var classModifier = GetAttributeValue(root, "ClassModifier", XamlParser.X2006Uri, XamlParser.X2009Uri);
		accessModifier = classModifier?.ToLowerInvariant().Replace("notpublic", "internal") ?? "public"; // notpublic is WPF for internal

		return true;
	}

#if !NET12_0_OR_GREATER
	//true, unless explicitely false
	static bool GetXamlCompilationProcessingInstruction(XmlDocument xmlDoc)
	{
		if (xmlDoc.SelectSingleNode("processing-instruction('xaml-comp')") is not XmlProcessingInstruction instruction)
			return true;

		var parts = instruction.Data.Split(' ', '=');
		var indexOfCompile = Array.IndexOf(parts, "compile");
		if (indexOfCompile != -1)
			return !parts[indexOfCompile + 1].Trim('"', '\'').Equals("false", StringComparison.OrdinalIgnoreCase);

		return true;
	}
#endif

	internal static string GetWarningDisable(XmlDocument xmlDoc)
	{
		var warnings = new List<string>();
		var xamlCompNodes = xmlDoc.SelectNodes("processing-instruction('xaml-comp')");
		foreach (var xamlCompNode in xamlCompNodes)
		{
			if (xamlCompNode is not XmlProcessingInstruction xpi)
				continue;
			var parts = xpi.Data.Split(' ', '=');
			var indexOfWarningDisable = Array.IndexOf(parts, "warning-disable");
			if (indexOfWarningDisable != -1)
				warnings.Add(parts[indexOfWarningDisable + 1].Trim('"', '\''));
		}
		return string.Join(", ", warnings);
	}

	readonly record struct FieldReconciliation(HashSet<string> GhostFieldNames, HashSet<string> ConditionallyAssignedFieldNames);

	/// <summary>Keeps generated fields additive across Hot Reload edits to avoid EnC field rude edits.</summary>
	static FieldReconciliation ReconcileNamedFieldsForHotReload(ProjectItem projItem, Compilation compilation, ref IEnumerable<(string name, string type, string accessModifier, XmlType xmlType, string xamlName)>? namedFields)
	{
		var ghostFieldNames = new HashSet<string>(System.StringComparer.Ordinal);
		var conditionallyAssignedFieldNames = new HashSet<string>(System.StringComparer.Ordinal);

		if (!projItem.EnableIncrementalHotReload || namedFields == null)
			return new(ghostFieldNames, conditionallyAssignedFieldNames);

		var assemblyName = compilation.AssemblyName ?? string.Empty;
		var targetFramework = projItem.TargetFramework ?? string.Empty;
		var stateKey = projItem.HotReloadStateKey;

		var currentFields = namedFields
			.Where(static field => IsValidFieldName(field.name) && !string.IsNullOrWhiteSpace(field.type))
			.ToList();
		var currentByName = new Dictionary<string, (string name, string type, string accessModifier, XmlType xmlType, string xamlName)>(System.StringComparer.Ordinal);
		foreach (var field in currentFields)
			currentByName[field.name] = field;

		var accumulated = XamlHotReloadState.GetAccumulatedCodeBehindFields(assemblyName, targetFramework, stateKey, projItem.HotReloadSessionToken)
			?? new Dictionary<string, HotReloadFieldContract>(System.StringComparer.Ordinal);

		var merged = new List<(string name, string type, string accessModifier, XmlType xmlType, string xamlName)>();
		var mergedNames = new HashSet<string>(System.StringComparer.Ordinal);

		// Preserve prior declarations and order.
		foreach (var kvp in accumulated)
		{
			var hasCurrentField = currentByName.TryGetValue(kvp.Key, out var current);
			merged.Add((kvp.Key, kvp.Value.Type, kvp.Value.AccessModifier, kvp.Value.XmlType, hasCurrentField ? current.xamlName : kvp.Key));
			mergedNames.Add(kvp.Key);

			if (!hasCurrentField)
				ghostFieldNames.Add(kvp.Key);
			else if (!string.Equals(current.type, kvp.Value.Type, StringComparison.Ordinal))
				conditionallyAssignedFieldNames.Add(kvp.Key);
		}

		// Append new fields without changing prior declarations.
		foreach (var field in currentFields)
		{
			if (mergedNames.Add(field.name))
				merged.Add(field);
		}

		namedFields = merged;

		var toPersist = new Dictionary<string, HotReloadFieldContract>(System.StringComparer.Ordinal);
		foreach (var (fname, ftype, faccess, xmlType, _) in merged)
			toPersist[fname] = new(ftype, faccess, xmlType);
		XamlHotReloadState.SetAccumulatedCodeBehindFields(assemblyName, targetFramework, stateKey, toPersist, projItem.HotReloadSessionToken);

		return new(ghostFieldNames, conditionallyAssignedFieldNames);
	}

	static bool IsValidFieldName(string name) =>
		!string.IsNullOrWhiteSpace(name)
		&& (SyntaxFacts.IsValidIdentifier(name) || SyntaxFacts.GetKeywordKind(name) != SyntaxKind.None);

	static IEnumerable<(string name, string type, string accessModifier, XmlType xmlType, string xamlName)> GetNamedFields(XmlNode root, XmlNamespaceManager nsmgr, Compilation compilation, AssemblyAttributes xmlnsCache, IDictionary<XmlType, INamedTypeSymbol> typeCache, CancellationToken cancellationToken, Action<Diagnostic>? reportDiagnostic)
	{
		var xPrefix = nsmgr.LookupPrefix(XamlParser.X2006Uri) ?? nsmgr.LookupPrefix(XamlParser.X2009Uri);
		if (xPrefix == null)
		{
			yield break;
		}

		XmlNodeList names =
			root.SelectNodes(
				"//*[@" + xPrefix + ":Name" +
				"][not(ancestor:: __f__:DataTemplate) and not(ancestor:: __f__:ControlTemplate) and not(ancestor:: __f__:Style) and not(ancestor:: __f__:VisualStateManager.VisualStateGroups)" +
				"and not(ancestor:: __g__:DataTemplate) and not(ancestor:: __g__:ControlTemplate) and not(ancestor:: __g__:Style) and not(ancestor:: __g__:VisualStateManager.VisualStateGroups)]", nsmgr);
		foreach (XmlNode node in names)
		{
			cancellationToken.ThrowIfCancellationRequested();

			var xamlName = GetAttributeValue(node, "Name", XamlParser.X2006Uri, XamlParser.X2009Uri) ?? throw new Exception();
			var typeArguments = GetAttributeValue(node, "TypeArguments", XamlParser.X2006Uri, XamlParser.X2009Uri);
			var fieldModifier = GetAttributeValue(node, "FieldModifier", XamlParser.X2006Uri, XamlParser.X2009Uri);

			var xmlType = new XmlType(node.NamespaceURI, node.LocalName,
									  typeArguments != null
									  ? TypeArgumentsParser.ParseExpression(typeArguments, GetNamespacesInScope(node, root, nsmgr), null)
									  : null);

			var accessModifier = fieldModifier?.ToLowerInvariant().Replace("notpublic", "internal") ?? "private"; //notpublic is WPF for internal
			if (!accessModifiers.Contains(accessModifier)) //quick validation
				accessModifier = "private";

			// Fields use trimmed identifiers, but runtime namescope lookups must preserve the XAML name.
			yield return (xamlName.Trim(), xmlType.GetTypeSymbol(reportDiagnostic, compilation, xmlnsCache, typeCache)?.ToFQDisplayString() ?? "", accessModifier, xmlType, xamlName);
		}
	}

	static XmlNamespaceManager GetNamespacesInScope(XmlNode node, XmlNode root, XmlNamespaceManager rootNamespaces)
	{
		var namespaces = new XmlNamespaceManager(rootNamespaces.NameTable);
		foreach (var entry in rootNamespaces.GetNamespacesInScope(XmlNamespaceScope.ExcludeXml))
			namespaces.AddNamespace(entry.Key, entry.Value);

		var ancestors = new Stack<XmlNode>();
		for (var current = node; current != null && current != root; current = current.ParentNode)
			ancestors.Push(current);
		while (ancestors.Count > 0)
		{
			foreach (XmlAttribute attribute in ancestors.Pop().Attributes!)
			{
				if (attribute.Name == "xmlns")
					namespaces.AddNamespace("", attribute.Value);
				else if (attribute.Prefix == "xmlns")
					namespaces.AddNamespace(attribute.LocalName, attribute.Value);
			}
		}
		return namespaces;
	}

	static string? GetAttributeValue(XmlNode node, string localName, params string[] namespaceURIs)
	{
		if (node == null)
			throw new ArgumentNullException(nameof(node));

		if (localName == null)
			throw new ArgumentNullException(nameof(localName));

		if (namespaceURIs == null)
			throw new ArgumentNullException(nameof(namespaceURIs));

		foreach (var namespaceURI in namespaceURIs)
		{
			var attr = node.Attributes[localName, namespaceURI];
			if (attr == null)
			{
				continue;
			}

			return attr.Value;
		}
		return null;
	}

